# Bundles src/xpui.lua + src/main.lua into dist/xpware.lua (one file to paste into the executor)
$root = Split-Path -Parent $MyInvocation.MyCommand.Path
$lib  = [IO.File]::ReadAllText((Join-Path $root "src/xpui.lua"))
$main = [IO.File]::ReadAllText((Join-Path $root "src/main.lua"))

$out = "-- xpware bundle, generated by build.ps1 (edit src/, not this file)`nlocal Library = (function()`n$lib`nend)()`n`n$main"

New-Item -ItemType Directory -Force (Join-Path $root "dist") | Out-Null
[IO.File]::WriteAllText((Join-Path $root "dist/xpware.lua"), $out, (New-Object Text.UTF8Encoding $false))
Write-Host "built dist/xpware.lua"
